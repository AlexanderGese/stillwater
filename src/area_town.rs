#[cfg(test)]
mod tests {
    use super::*;
    use crate::geom::Point;
    use crate::tile::Tile;

    #[test]
    fn builds_and_is_big_enough() {
        let a = town_area();
        assert!(a.map.w >= 64 && a.map.h >= 24);
    }

    #[test]
    fn start_is_walkable() {
        let a = town_area();
        assert!(a.map.walkable(a.start));
    }

    #[test]
    fn has_a_notice_board() {
        let a = town_area();
        let mut count = 0;
        for y in 0..a.map.h {
            for x in 0..a.map.w {
                if a.map.get(Point::new(x, y)) == Tile::Sign {
                    count += 1;
                }
            }
        }
        assert!(count >= 1);
    }

    #[test]
    fn south_edge_has_a_walkable_opening() {
        let a = town_area();
        let mut found = false;
        for x in 0..a.map.w {
            if a.map.walkable(Point::new(x, a.map.h - 1)) {
                found = true;
            }
        }
        assert!(found);
    }
}
